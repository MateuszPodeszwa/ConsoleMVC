#nullable enable

using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text;
using ConsoleMVC.Generators.Parsing;
using ConsoleMVC.Generators.Schema;
using ConsoleMVC.Generators.Syntax;

namespace ConsoleMVC.Generators.Emit;

/// <summary>
/// Generates the C# source of a <c>ConsoleView&lt;TModel&gt;</c> subclass from a parsed <see cref="CvwDocument"/>.
/// </summary>
/// <remarks>
/// <para>
/// User code (C# segments, expressions, the model type and <c>@using</c> namespaces) is wrapped in
/// <c>#line</c> directives so that compiler errors and debugger breakpoints map to the <c>.cvw</c> file.
/// Generated scaffolding is marked <c>#line hidden</c>.
/// </para>
/// <para>
/// Each markup element becomes a block that constructs its runtime element, assigns attributes, adds its
/// children and finally either renders it (top level) or adds it to its parent element.
/// </para>
/// </remarks>
/// <example>
/// <code>
/// string source = ViewEmitter.Emit(document, viewInfo);
/// </code>
/// </example>
internal sealed class ViewEmitter
{
    /// <summary>Namespaces always imported by generated views.</summary>
    private static readonly string[] DefaultUsings =
    [
        "System",
        "System.Collections.Generic",
        "System.Linq",
        "ConsoleMVC.Mvc"
    ];

    private const string TextElementType = "global::ConsoleMVC.Rendering.TextElement";

    private const string UsingKeyword = "using ";

    private const string PublicKeyword = "public ";

    /// <summary>
    /// Prefix of generated local variables. Identifiers starting with <c>__cvw_</c> are reserved in views
    /// (documented in the C-View Markup guide).
    /// </summary>
    private const string VariablePrefix = "__cvw_e";

    private readonly CvwDocument _document;
    private readonly ViewInfo _info;
    private readonly LineMap _lines;
    private readonly string _quotedPath;
    private readonly StringBuilder _output = new();
    private int _variableCounter;

    private ViewEmitter(CvwDocument document, ViewInfo info)
    {
        _document = document;
        _info = info;
        _lines = new LineMap(document.Text);
        _quotedPath = LinePath(info.FilePath);
    }

    /// <summary>
    /// Generates the view class source.
    /// </summary>
    /// <param name="document">The parsed view (must be free of errors).</param>
    /// <param name="info">The view's namespace and class name.</param>
    /// <returns>The complete C# source file.</returns>
    public static string Emit(CvwDocument document, ViewInfo info) => new ViewEmitter(document, info).EmitView();

    private string EmitView()
    {
        Line("// <auto-generated>");
        Line($"// Generated by ConsoleMVC ViewEngine from {_info.ControllerName}/{_info.ClassName}.cvw");
        Line("// Do not modify this file directly — edit the .cvw source instead.");
        Line("// </auto-generated>");
        Line("#nullable restore");
        Line("#pragma warning disable CS1591 // generated views have no XML documentation");

        foreach (var name in DefaultUsings)
            Line($"using {name};");

        foreach (var directive in _document.Usings.Where(u => !DefaultUsings.Contains(u.Value)))
        {
            // Indent so that the namespace lands on its column in the .cvw file (it follows "@using ")
            var (line, column) = _lines.GetPosition(directive.Span.Start);
            EnsureNewLine();
            _output.Append("#line ").Append((line + 1).ToString(CultureInfo.InvariantCulture)).Append(' ').Append(_quotedPath).Append('\n');
            _output.Append(' ', Math.Max(column - UsingKeyword.Length, 0)).Append(UsingKeyword).Append(directive.Value).Append(";\n");
            Hidden();
        }

        Line("");
        Line($"namespace {_info.Namespace}");
        Line("{");
        Line($"    public partial class {_info.ClassName} : global::ConsoleMVC.Mvc.ConsoleView<{ModelType()}>");
        Line("    {");

        foreach (var inject in _document.Injects)
            EmitInject(inject);

        // Map the method to the first line so "not all code paths return a value" points at the .cvw file
        Map(_document.Model?.Span.Start ?? 0, includeColumn: false);
        Line($"        public override global::ConsoleMVC.Mvc.NavigationResult Render({ModelType()} Model)");
        Hidden();
        Line("        {");

        EmitNodes(_document.Body, parentVariable: null);

        Line("#line default");
        Line("        }");
        Line("    }");
        Line("}");

        return _output.ToString();
    }

    /// <summary>
    /// Emits the property for an <c>@inject</c> directive, indented so that its type lands on the type's column in
    /// the <c>.cvw</c> file (it always follows <c>"@inject "</c>, which is longer than <c>"public "</c>).
    /// </summary>
    private void EmitInject(InjectDirective inject)
    {
        Line("        [global::ConsoleMVC.Mvc.InjectAttribute]");

        var (line, column) = _lines.GetPosition(inject.Type.Span.Start);
        EnsureNewLine();
        _output.Append("#line ").Append((line + 1).ToString(CultureInfo.InvariantCulture)).Append(' ').Append(_quotedPath).Append('\n');
        _output.Append(' ', Math.Max(column - PublicKeyword.Length, 0)).Append(PublicKeyword)
            .Append(inject.Type.Value).Append(' ').Append(inject.Name.Value)
            .Append(" { get; private set; } = default!;\n");
        Hidden();
    }

    // ------------------------------------------------------------------ nodes

    /// <summary>
    /// Emits a sequence of nodes. Runs of text and expressions inside a block container are wrapped in an
    /// implicit text element.
    /// </summary>
    /// <param name="nodes">The nodes to emit.</param>
    /// <param name="parentVariable">The variable of the containing element, or <see langword="null"/> at top level.</param>
    private void EmitNodes(IReadOnlyList<Node> nodes, string? parentVariable)
    {
        var index = 0;
        while (index < nodes.Count)
        {
            switch (nodes[index])
            {
                case CodeNode code:
                    EmitCode(code);
                    index++;
                    break;

                case ElementNode element:
                    EmitElement(element, parentVariable);
                    index++;
                    break;

                default:
                    // Text or expression directly inside a block container
                    var run = new List<Node>();
                    while (index < nodes.Count && nodes[index] is TextNode or ExpressionNode)
                        run.Add(nodes[index++]);

                    EmitImplicitText(run, parentVariable!);
                    break;
            }
        }
    }

    private void EmitCode(CodeNode code)
    {
        if (string.IsNullOrWhiteSpace(code.Code))
            return;

        Map(code.Span.Start, includeColumn: true);
        _output.Append(code.Code).Append('\n');
        Hidden();
    }

    private void EmitElement(ElementNode element, string? parentVariable)
    {
        var variable = NewVariable();

        Line("{");
        Line($"var {variable} = new {element.Schema.RuntimeType}();");

        foreach (var initialiser in element.Schema.Initialisers)
            Line($"{variable}.{initialiser};");

        foreach (var attribute in element.Attributes)
            _output.Append(variable).Append('.').Append(attribute.Schema.Property).Append(" = ").Append(AttributeValue(attribute)).Append(";\n");

        switch (element.Schema.Content)
        {
            case ContentModel.Inline:
                EmitInlineContent(element.Children, variable);
                break;
            case ContentModel.Block:
            case ContentModel.Elements:
                EmitNodes(element.Children, variable);
                break;
        }

        Line(parentVariable is null
            ? string.Format(CultureInfo.InvariantCulture, element.Schema.TopLevelStatement, variable)
            : $"{parentVariable}.Add({variable});");
        Line("}");
    }

    private void EmitImplicitText(IReadOnlyList<Node> run, string parentVariable)
    {
        var items = NormaliseInline(run);
        if (items.Count == 0)
            return; // whitespace between elements

        var variable = NewVariable();
        Line("{");
        Line($"var {variable} = new {TextElementType}();");
        EmitInlineItems(items, variable);
        Line($"{parentVariable}.Add({variable});");
        Line("}");
    }

    private void EmitInlineContent(IReadOnlyList<Node> children, string variable) =>
        EmitInlineItems(NormaliseInline(children), variable);

    private void EmitInlineItems(IEnumerable<Node> items, string variable)
    {
        foreach (var item in items)
        {
            switch (item)
            {
                case TextNode text:
                    Line($"{variable}.AppendText({CSharpLiteral.String(text.Text)});");
                    break;

                case ExpressionNode expression:
                    _output.Append(variable).Append(".AppendValue(").Append(MapExpression(expression.Code, expression.Span.Start)).Append(");\n");
                    break;

                case ElementNode lineBreak:
                    EmitInlineLineBreak(lineBreak, variable);
                    break;
            }
        }
    }

    /// <summary>Emits <c>&lt;br /&gt;</c> inside text as one or more <c>AppendLineBreak()</c> calls.</summary>
    private void EmitInlineLineBreak(ElementNode lineBreak, string variable)
    {
        var count = lineBreak.Attributes.FirstOrDefault();

        if (count is null)
        {
            Line($"{variable}.AppendLineBreak();");
        }
        else if (count.LiteralCode is not null)
        {
            var repeat = int.Parse(count.LiteralCode, CultureInfo.InvariantCulture);
            for (var i = 0; i < repeat; i++)
                Line($"{variable}.AppendLineBreak();");
        }
        else
        {
            var counter = NewVariable();
            _output.Append("for (var ").Append(counter).Append(" = 0; ").Append(counter).Append(" < ")
                .Append(AttributeValue(count)).Append("; ").Append(counter).Append("++) ")
                .Append(variable).Append(".AppendLineBreak();\n");
        }
    }

    /// <summary>
    /// Applies HTML-like whitespace rules to inline content: whitespace runs collapse to a single space, and
    /// whitespace at the start, the end and around line breaks is removed. Empty text items are dropped.
    /// </summary>
    private static List<Node> NormaliseInline(IReadOnlyList<Node> nodes)
    {
        var items = new List<Node>();
        foreach (var node in nodes)
        {
            items.Add(node is TextNode text ? new TextNode(CollapseWhitespace(text.Text), text.Span) : node);
        }

        for (var i = 0; i < items.Count; i++)
        {
            if (items[i] is not TextNode text)
                continue;

            var value = text.Text;
            if (i == 0 || items[i - 1] is ElementNode)
                value = value.TrimStart(' ');
            if (i == items.Count - 1 || items[i + 1] is ElementNode)
                value = value.TrimEnd(' ');

            items[i] = new TextNode(value, text.Span);
        }

        items.RemoveAll(n => n is TextNode { Text.Length: 0 });
        return items;
    }

    private static string CollapseWhitespace(string text)
    {
        var builder = new StringBuilder(text.Length);
        var inWhitespace = false;

        foreach (var c in text)
        {
            // Non-breaking spaces (&nbsp;) are deliberately preserved
            if (c is ' ' or '\t' or '\r' or '\n')
            {
                if (!inWhitespace)
                    builder.Append(' ');
                inWhitespace = true;
            }
            else
            {
                builder.Append(c);
                inWhitespace = false;
            }
        }

        return builder.ToString();
    }

    // ------------------------------------------------------------------ attributes and mapping

    /// <summary>Returns the C# code assigned to an attribute's property.</summary>
    private string AttributeValue(AttributeNode attribute)
    {
        if (attribute.LiteralCode is not null)
            return attribute.LiteralCode;

        var type = attribute.Schema.Type;

        // A single expression: assign it (type-checked by the compiler)
        if (attribute.Parts.Count == 1)
            return type.WrapExpression(MapExpression(attribute.Parts[0].Text, attribute.Parts[0].Span.Start));

        // Text mixed with expressions (string attributes only): concatenate
        var pieces = attribute.Parts.Select(part => part.IsExpression
            ? type.WrapExpression(MapExpression(part.Text, part.Span.Start))
            : CSharpLiteral.String(part.Text));

        return "string.Concat(new string[] { " + string.Join(", ", pieces) + " })";
    }

    /// <summary>Wraps an expression in <c>#line</c> directives so errors point at its position in the <c>.cvw</c> file.</summary>
    private string MapExpression(string code, int offset)
    {
        var (line, column) = _lines.GetPosition(offset);
        return "\n#line " + (line + 1).ToString(CultureInfo.InvariantCulture) + " " + _quotedPath + "\n"
               + new string(' ', column) + code + "\n#line hidden\n";
    }

    /// <summary>
    /// Writes a <c>#line</c> directive for <paramref name="offset"/>. With <paramref name="includeColumn"/>, the
    /// following text is indented so its columns also match the source.
    /// </summary>
    private void Map(int offset, bool includeColumn)
    {
        var (line, column) = _lines.GetPosition(offset);
        EnsureNewLine();
        _output.Append("#line ").Append((line + 1).ToString(CultureInfo.InvariantCulture)).Append(' ').Append(_quotedPath).Append('\n');

        if (includeColumn)
            _output.Append(' ', column);
    }

    private void Hidden()
    {
        EnsureNewLine();
        _output.Append("#line hidden\n");
    }

    private void Line(string text)
    {
        EnsureNewLine();
        _output.Append(text).Append('\n');
    }

    private void EnsureNewLine()
    {
        if (_output.Length > 0 && _output[_output.Length - 1] != '\n')
            _output.Append('\n');
    }

    private string ModelType()
    {
        if (_document.Model is null)
            return CvwDocument.DefaultModelType;

        return MapExpression(_document.Model.Value, _document.Model.Span.Start);
    }

    private string NewVariable() => VariablePrefix + (++_variableCounter).ToString(CultureInfo.InvariantCulture);

    /// <summary>
    /// Quotes a file path for a <c>#line</c> directive. The compiler takes the text between the quotes literally
    /// (escape sequences are not processed), so the path is written as-is; only characters that cannot appear
    /// inside the directive are removed.
    /// </summary>
    private static string LinePath(string path) =>
        "\"" + path.Replace("\"", "").Replace("\r", "").Replace("\n", "") + "\"";
}
